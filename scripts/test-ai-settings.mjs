import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createServer } from 'node:http';
import assert from 'node:assert/strict';
import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '..'), output = resolve(root, '.cache/qa/ai-settings-browser'), temporary = resolve(root, '.cache/playwright/tmp');
await Promise.all([output, temporary].map(path => mkdir(path, { recursive: true })));
process.env.TEMP = temporary; process.env.TMP = temporary;
process.env.PLAYWRIGHT_BROWSERS_PATH = resolve(root, '.cache/playwright/browsers');
await build({ entryPoints: [resolve(root, 'tests/palettes-fixture.ts')], outfile: resolve(output, 'app.js'), bundle: true, format: 'iife', target: 'chrome100' });
await writeFile(resolve(output, 'index.html'), '<!doctype html><html lang="ru"><meta charset="utf-8"><link rel="stylesheet" href="/app.css"><div id="root"></div><script src="/app.js"></script></html>');
const server = createServer(async (request, response) => {
  const file = request.url === '/app.js' ? 'app.js' : request.url === '/app.css' ? 'app.css' : 'index.html';
  response.setHeader('Content-Type', file.endsWith('.js') ? 'text/javascript' : file.endsWith('.css') ? 'text/css' : 'text/html');
  response.end(await readFile(resolve(output, file)));
});
await new Promise(done => server.listen(0, '127.0.0.1', done));
const { chromium } = await import('playwright');
const browser = await chromium.launch({ channel: 'msedge', headless: true, env: { ...process.env } });
const page = await browser.newPage({ viewport: { width: 520, height: 840 } }), errors = [];
page.setDefaultTimeout(4000); page.on('pageerror', error => errors.push(error.message));
const base = `http://127.0.0.1:${server.address().port}`;
try {
  await page.goto(base);
  await page.getByRole('button', { name: 'Настройки AI', exact: true }).click();
  await page.getByRole('dialog', { name: 'Подключение AI', exact: true }).waitFor();
  assert.equal(await page.locator('input[type=file][accept=".txt"]').count(), 0);
  await page.getByRole('combobox', { name: 'Провайдер', exact: true }).click();
  await page.getByRole('option', { name: 'OpenAI', exact: true }).click();
  assert.equal(await page.getByRole('textbox', { name: 'Базовый адрес API', exact: true }).inputValue(), 'https://api.openai.com/v1');
  await page.getByRole('combobox', { name: 'Модель', exact: true }).fill('chosen-chat-model');
  await page.getByRole('textbox', { name: 'API-ключ', exact: true }).fill('test-openai-key');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await page.getByRole('dialog', { name: 'Подключение AI', exact: true }).waitFor({ state: 'hidden' });
  await page.getByRole('textbox', { name: 'Идея или заголовок', exact: true }).fill('Обучение через практику');
  await page.getByRole('button', { name: 'Создать композиции', exact: true }).click();
  await page.getByText('Создано вариантов: 1', { exact: true }).waitFor();
  const sent = JSON.parse(await page.locator('html').getAttribute('data-ai-request'));
  assert.equal(sent.url, 'https://api.openai.com/v1/chat/completions');
  assert.equal(sent.body.model, 'chosen-chat-model'); assert.ok(sent.body.max_completion_tokens); assert.equal(sent.body.thinking, undefined);
  console.log('OK OpenAI: произвольный ключ и ID модели → правильный запрос без параметров DeepSeek');
  await page.getByRole('button', { name: 'Настройки AI', exact: true }).click();
  const key = page.getByRole('textbox', { name: 'API-ключ', exact: true });
  assert.equal(await key.inputValue(), '');
  await page.getByRole('combobox', { name: 'Модель', exact: true }).fill('another-chat-model');
  assert.equal(await page.getByRole('button', { name: 'Сохранить', exact: true }).isEnabled(), true);
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await page.getByRole('dialog', { name: 'Подключение AI', exact: true }).waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Создать композиции', exact: true }).click();
  await page.waitForFunction(() => JSON.parse(document.documentElement.dataset.aiRequest || '{}').body?.model === 'another-chat-model');
  console.log('OK смена модели внутри провайдера использует заданный ключ');

  await page.getByRole('button', { name: 'Настройки AI', exact: true }).click();
  await key.fill('do-not-transfer');
  await page.getByRole('combobox', { name: 'Провайдер', exact: true }).click();
  await page.getByRole('option', { name: 'OpenAI-совместимый сервис', exact: true }).click();
  assert.equal(await key.inputValue(), '');
  assert.equal(await page.getByRole('button', { name: 'Сохранить', exact: true }).isDisabled(), true);
  await page.getByRole('textbox', { name: 'Базовый адрес API', exact: true }).fill('https://proxy.example/v1/chat/completions');
  await page.getByRole('combobox', { name: 'Модель', exact: true }).fill('vendor/custom-model');
  await key.fill('test-custom-key');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await page.getByRole('dialog', { name: 'Подключение AI', exact: true }).waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Создать композиции', exact: true }).click();
  await page.waitForFunction(() => JSON.parse(document.documentElement.dataset.aiRequest || '{}').url === 'https://proxy.example/v1/chat/completions');
  const custom = JSON.parse(await page.locator('html').getAttribute('data-ai-request'));
  assert.equal(custom.body.model, 'vendor/custom-model'); assert.equal(custom.body.thinking, undefined); assert.equal(custom.body.response_format, undefined);
  await page.reload();
  await page.getByRole('button', { name: 'Настройки AI', exact: true }).click();
  assert.equal(await page.getByRole('textbox', { name: 'Базовый адрес API', exact: true }).inputValue(), 'https://proxy.example/v1');
  assert.equal(await page.getByRole('combobox', { name: 'Модель', exact: true }).inputValue(), 'vendor/custom-model');
  assert.equal(await key.inputValue(), '');
  assert.equal(await page.getByRole('button', { name: 'Сохранить', exact: true }).isDisabled(), true);
  const persisted = await page.evaluate(() => localStorage.getItem('mixer-ai-config-v1'));
  assert.equal(persisted.includes('test-custom-key'), false); assert.equal(persisted.includes('apiKey'), false);
  await page.screenshot({ path: resolve(output, 'settings.png') });
  console.log('OK собственный endpoint, смена сервиса без переноса ключа и восстановление только публичных настроек');
  assert.deepEqual(errors, []);
} finally { await browser.close(); await new Promise(done => server.close(done)); }
