import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createServer } from 'node:http';
import assert from 'node:assert/strict';
import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '..'), output = resolve(root, '.cache/qa/ai-browser'), temporary = resolve(root, '.cache/playwright/tmp');
await Promise.all([output, temporary].map(path => mkdir(path, { recursive: true })));
process.env.TEMP = temporary; process.env.TMP = temporary;
process.env.PLAYWRIGHT_BROWSERS_PATH = resolve(root, '.cache/playwright/browsers');
await build({ entryPoints: [resolve(root, 'tests/palettes-fixture.ts')], outfile: resolve(output, 'app.js'), bundle: true, format: 'iife', target: 'chrome100' });
await writeFile(resolve(output, 'index.html'), '<!doctype html><html lang="ru"><meta charset="utf-8"><link rel="stylesheet" href="/app.css"><div id="root"></div><script src="/app.js"></script></html>');
const server = createServer(async (request, response) => {
  const file = request.url === '/app.js' ? 'app.js' : request.url === '/app.css' ? 'app.css' : 'index.html';
  response.setHeader('Content-Type', file.endsWith('.js') ? 'text/javascript' : file.endsWith('.css') ? 'text/css' : 'text/html');
  response.end(await readFile(resolve(output, file)));
});
await new Promise(done => server.listen(0, '127.0.0.1', done));
const { chromium } = await import('playwright');
const browser = await chromium.launch({ channel: 'msedge', headless: true, env: { ...process.env } });
const page = await browser.newPage({ viewport: { width: 520, height: 840 } }), errors = [];
page.setDefaultTimeout(4000); page.on('pageerror', error => errors.push(error.message));
const base = `http://127.0.0.1:${server.address().port}`;
try {
  await page.goto(base + '?connected&empty');
  await page.getByRole('heading', { name: 'Новая композиция', exact: true }).waitFor();
  const prompt = page.getByRole('group', { name: 'Запрос композиции', exact: true });
  await prompt.getByRole('textbox', { name: 'Тема или метафора', exact: true }).waitFor();
  for (const name of ['Количество вариантов', 'Формат', 'Детализация']) {
    assert.equal(await prompt.getByRole('combobox', { name, exact: true }).isVisible(), true);
  }
  const palette = page.getByRole('combobox', { name: 'Палитра', exact: true });
  const [paletteBounds, promptBounds] = await Promise.all([palette.boundingBox(), prompt.boundingBox()]);
  assert.ok(paletteBounds.y + paletteBounds.height <= promptBounds.y);
  assert.equal(await prompt.getByRole('combobox', { name: 'Палитра', exact: true }).count(), 0);
  await page.screenshot({ path: resolve(output, 'prompt.png') });
  assert.equal(await page.locator('.compose-items:visible').count(), 0);
  const suggestions = page.getByRole('listbox', { name: 'Подсказки из библиотеки', exact: true });
  const metaphor = prompt.getByRole('textbox', { name: 'Тема или метафора', exact: true });
  await metaphor.fill('Кни');
  assert.equal(await suggestions.count(), 0);
  await metaphor.fill('Обучение через практику. Используй @кни');
  await suggestions.getByRole('option', { name: 'Книга', exact: true }).waitFor();
  await metaphor.press('Enter');
  await prompt.getByRole('button', { name: 'Убрать предмет Книга', exact: true }).waitFor();
  const query = 'Обучение через практику. Используй Книга ';
  assert.equal(await metaphor.inputValue(), query);
  await page.getByRole('button', { name: 'Создать композиции', exact: true }).click();
  await page.getByText('Создано вариантов: 3', { exact: true }).waitFor();
  assert.equal(await metaphor.inputValue(), query);
  assert.equal(await prompt.getByRole('combobox', { name: 'Количество вариантов', exact: true }).innerText(), '3');
  const generated = JSON.parse(await page.locator('html').getAttribute('data-prompt-result'));
  assert.equal(generated.directions.length, 3);
  assert.equal(generated.directions.every(p => p.ids.includes('starter-2')), true);
  assert.equal(new Set(generated.directions.map(p => [...p.ids].sort().join(','))).size, 3);
  await page.screenshot({ path: resolve(output, 'result.png') });
  console.log('OK параметры в поле запроса → один запрос → разные составы → результат на том же экране');
  await palette.click();
  await page.getByRole('option', { name: 'Персик', exact: true }).click();
  await prompt.getByRole('combobox', { name: 'Формат', exact: true }).click();
  await page.getByRole('option', { name: 'Квадрат · 1080 × 1080', exact: true }).click();
  await prompt.getByRole('combobox', { name: 'Детализация', exact: true }).click();
  await page.getByRole('option', { name: 'S · Упрощённая', exact: true }).click();
  await prompt.getByRole('combobox', { name: 'Количество вариантов', exact: true }).click();
  await page.getByRole('option', { name: '2 варианта', exact: true }).click();
  await prompt.getByRole('button', { name: 'Создать композиции', exact: true }).click();
  await page.getByText('Создано вариантов: 2', { exact: true }).waitFor();
  await page.waitForFunction(() => JSON.parse(document.documentElement.dataset.promptResult || '{}').directions?.every(p => p.palette === 'peach'));
  const options = JSON.parse(await page.locator('html').getAttribute('data-created'));
  assert.deepEqual([options.width, options.height, options.detail], [1080, 1080, 'S']);
  await page.setViewportSize({ width: 400, height: 700 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await prompt.evaluate(node => node.scrollWidth <= node.clientWidth), true);
  await page.screenshot({ path: resolve(output, 'narrow.png') });
  await prompt.getByRole('button', { name: 'Убрать предмет Книга', exact: true }).click();
  assert.equal(await prompt.getByRole('group', { name: 'Предметы в запросе' }).count(), 0);
  assert.equal(await metaphor.inputValue(), query);
  console.log('OK фиксированная палитра во всех решениях и панель 400 px');

  await page.goto(base + '?empty');
  await prompt.getByRole('button', { name: 'Предметы', exact: true }).click();
  const itemInput = prompt.getByRole('textbox', { name: 'Названия предметов', exact: true });
  await itemInput.fill('кни');
  await suggestions.getByRole('option', { name: 'Книга', exact: true }).waitFor();
  await itemInput.press('Enter');
  await itemInput.fill('лам');
  await suggestions.getByRole('option', { name: 'Лампа', exact: true }).waitFor();
  await page.screenshot({ path: resolve(output, 'item-suggestions.png') });
  await suggestions.getByRole('option', { name: 'Лампа', exact: true }).click();
  await prompt.getByRole('button', { name: 'Убрать предмет Лампа', exact: true }).waitFor();
  await prompt.getByRole('button', { name: 'Создать композиции', exact: true }).click();
  await page.getByText('Создано вариантов: 3', { exact: true }).waitFor();
  assert.equal(await page.locator('html').getAttribute('data-ai-request'), null);
  const manual = JSON.parse(await page.locator('html').getAttribute('data-prompt-result'));
  assert.deepEqual(manual.directions.map(p => p.ids), Array.from({ length: 3 }, () => ['starter-2', 'starter-5']));
  console.log('OK предметы по буквам → выбор Enter и мышью → точный состав без AI');

  await page.goto(base + '?empty');
  await page.getByRole('textbox', { name: 'Тема или метафора', exact: true }).fill('Сложная задача и новые идеи');
  await page.getByRole('button', { name: 'Создать композиции', exact: true }).click();
  await page.getByRole('dialog', { name: 'Подключение AI', exact: true }).waitFor();
  await page.getByRole('textbox', { name: 'API-ключ', exact: true }).fill('test-key');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await page.getByText('Создано вариантов: 3', { exact: true }).waitFor();
  assert.equal(await page.getByRole('textbox', { name: 'Тема или метафора', exact: true }).inputValue(), 'Сложная задача и новые идеи');
  console.log('OK подключение ключа продолжает исходный запрос без повторного ввода');

  await page.goto(base + '?connected&ai-error');
  await page.getByRole('textbox', { name: 'Тема или метафора', exact: true }).fill('Новая идея');
  await page.getByRole('button', { name: 'Создать композиции', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'неизвестный предмет' }).waitFor();
  assert.equal(await page.locator('html').getAttribute('data-created'), null);
  assert.equal(await page.getByRole('button', { name: 'Создать композиции', exact: true }).isEnabled(), true);
  console.log('OK ошибочный AI-план не создаёт фреймы и сохраняет запрос');
  await page.goto(base);
  await page.getByRole('textbox', { name: 'Тема или метафора', exact: true }).fill('Новая идея');
  await page.getByRole('button', { name: 'Создать композиции', exact: true }).click();
  await page.getByRole('dialog', { name: 'Подключение AI', exact: true }).getByRole('button', { name: 'Закрыть панель', exact: true }).click();
  await page.getByRole('button', { name: 'Настройки AI', exact: true }).click();
  await page.getByRole('textbox', { name: 'API-ключ', exact: true }).fill('test-key');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await page.getByRole('dialog', { name: 'Подключение AI', exact: true }).waitFor({ state: 'hidden' });
  assert.equal(await page.locator('html').getAttribute('data-prompt-result'), null);
  console.log('OK отменённый запрос не возобновляется при последующем подключении');
  assert.deepEqual(errors, []);
} finally { await browser.close(); await new Promise(done => server.close(done)); }
